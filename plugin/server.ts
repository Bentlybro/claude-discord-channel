mcp.setRequestHandler(CallToolRequestSchema, async req => {
  const args = (req.params.arguments ?? {}) as Record<string, unknown>
  try {
    switch (req.params.name) {
      case 'reply': {
        const chat_id = args.chat_id as string
        const text = args.text as string
        const reply_to = args.reply_to as string | undefined
        const files = (args.files as string[] | undefined) ?? []
        // PATCHED(dispatch): no bot-to-bot loops (see bots read by allowlist)
        {
          const botSpokeLast = (lastInboundFromBot.get(chat_id) ?? 0) > Date.now() - 3 * 60_000
          let toBot = false
          if (reply_to) {
            try {
              const target = await fetchTextChannel(chat_id)
              const m = 'messages' in target ? await target.messages.fetch(reply_to) : null
              toBot = !!m && (m.author.bot || !!m.webhookId) && m.author.id !== client.user?.id
            } catch {}
          }
          if (toBot || botSpokeLast) {
            // PATCHED(dispatch): bot replies are rare (see dispatchBotReplyGate)
            const b = dispatchBots() as any
            const why = dispatchBotReplyGate(b, chat_id, reply_to, toBot, Date.now())
            if (why) throw new Error(why)
            try {
              writeFileSync(BOTS_FILE + '.tmp', JSON.stringify(b, null, 2) + '\n')
              renameSync(BOTS_FILE + '.tmp', BOTS_FILE)
            } catch {}
          }
        }

        const ch = await fetchAllowedChannel(chat_id)
        if (!('send' in ch)) throw new Error('channel is not sendable')

        for (const f of files) {
          assertSendable(f)
          const st = statSync(f)
          if (st.size > MAX_ATTACHMENT_BYTES) {
            throw new Error(`file too large: ${f} (${(st.size / 1024 / 1024).toFixed(1)}MB, max 25MB)`)
          }
        }
        if (files.length > 10) throw new Error('Discord allows max 10 attachments per message')

        const access = loadAccess()
        const limit = Math.max(1, Math.min(access.textChunkLimit ?? MAX_CHUNK_LIMIT, MAX_CHUNK_LIMIT))
        // PATCHED(dispatch): split at words, files on the last part. 2026-10-05: a long reply was cut
        // mid-word ('PENDING s' / 'ubmissions') and its files landed on a middle part. Default to paragraph,
        // then line, then word boundaries; attach files to the final part, after all the text.
        const mode = access.chunkMode ?? 'newline'
        const replyMode = access.replyToMode ?? 'first'
        // PATCHED(dispatch): bare PR numbers become links. `#14799` -> a GitHub link, but not inside [..],
        // a URL, <..> or a code span. After the DM size check above, so a link never pushes a short DM over it.
        const chunks = chunk(dispatchLinkPRs(text), limit, mode)
        const sentIds: string[] = []

        try {
          for (let i = 0; i < chunks.length; i++) {
            const shouldReplyTo =
              reply_to != null &&
              replyMode !== 'off' &&
              (replyMode === 'all' || i === 0)
            const sent = await ch.send({
              content: chunks[i],
              ...(i === chunks.length - 1 && files.length > 0 ? { files } : {}),
              ...(shouldReplyTo
                ? { reply: { messageReference: reply_to, failIfNotExists: false } }
                : {}),
            })
            noteSent(sent.id)
            sentIds.push(sent.id)
          }
        } catch (err) {
          const msg = err instanceof Error ? err.message : String(err)
          throw new Error(`reply failed after ${sentIds.length} of ${chunks.length} chunk(s) sent: ${msg}`)
        }
        dispatchTouchEngaged(chat_id)

        const result =
          sentIds.length === 1
            ? `sent (id: ${sentIds[0]})`
            : `sent ${sentIds.length} parts (ids: ${sentIds.join(', ')})`
        return { content: [{ type: 'text', text: result }] }
      }
      case 'fetch_messages': {
        const ch = await fetchAllowedChannel(args.channel as string)
        const limit = Math.min((args.limit as number) ?? 20, 100)
        const msgs = await ch.messages.fetch({ limit })
        const me = client.user?.id
        const arr = [...msgs.values()].reverse()
        const out =
          arr.length === 0
            ? '(no messages)'
            : arr
                .map(m => {
                  const who = m.author.id === me ? 'me' : m.author.username
                  const atts = m.attachments.size > 0 ? ` +${m.attachments.size}att` : ''
                  // Tool result is newline-joined; multi-line content forges
                  // adjacent rows. History includes ungated senders (no-@mention
                  // messages in an opted-in channel never hit the gate but
                  // still live in channel history).
                  const text = dispatchMessageText(m).replace(/[\r\n]+/g, ' ⏎ ')
                  return `[${m.createdAt.toISOString()}] ${who}: ${text}  (id: ${m.id}${atts})`
                })
                .join('\n')
        return { content: [{ type: 'text', text: out }] }
      }
      case 'react': {
        const ch = await fetchAllowedChannel(args.chat_id as string)
        const msg = await ch.messages.fetch(args.message_id as string)
        await msg.react(args.emoji as string)
        return { content: [{ type: 'text', text: 'reacted' }] }
      }
      case 'edit_message': {
        const ch = await fetchAllowedChannel(args.chat_id as string)
        const msg = await ch.messages.fetch(args.message_id as string)
        const edited = await msg.edit(dispatchLinkPRs(args.text as string))
        return { content: [{ type: 'text', text: `edited (id: ${edited.id})` }] }
      }
      case 'download_attachment': {
        const ch = await fetchAllowedChannel(args.chat_id as string)
        const msg = await ch.messages.fetch(args.message_id as string)
        if (msg.attachments.size === 0) {
          return { content: [{ type: 'text', text: 'message has no attachments' }] }
        }
        const lines: string[] = []
        for (const att of msg.attachments.values()) {
          const path = await downloadAttachment(att)
          const kb = (att.size / 1024).toFixed(0)
          lines.push(`  ${path}  (${safeAttName(att)}, ${att.contentType ?? 'unknown'}, ${kb}KB)`)
        }
        return {
          content: [{ type: 'text', text: `downloaded ${lines.length} attachment(s):\n${lines.join('\n')}` }],
        }
      }
      default:
        return {
          content: [{ type: 'text', text: `unknown tool: ${req.params.name}` }],
          isError: true,
        }
    }
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err)
    return {
      content: [{ type: 'text', text: `${req.params.name} failed: ${msg}` }],
      isError: true,
    }
  }
})

